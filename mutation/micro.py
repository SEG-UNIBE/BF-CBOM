"""Generate the micro projects (experiments/corpus/micro/{java,python,go}) and ground truth from snippet catalogs.

`python -m mutation.micro` writes the checked-in project files and `experiments/corpus/micro/ground_truth.yaml`.
`tests/test_micro_projects.py` fails when they drift from what this module generates. One function per expected item
(a catalog snippet with its `expected` record) and per decoy (the catalog's `decoys:`, code that names or resembles
cryptography without using it; the mutation harness plants the same ones), with neutral names (`step01` ...) so that
no signature or call names an algorithm, and `main` calling them all.
An item's lines are its function's body (decided 2026-10-22: a tool finds the use wherever in it it points), so the
items never share a line and no record can land on a neighbour's.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

from .catalog import Catalog, Snippet, load_catalog, placeholders, render

ROOT = Path(__file__).resolve().parents[1]
MICRO_DIR = ROOT / "experiments" / "corpus" / "micro"
TRUTH_FILE = MICRO_DIR / "ground_truth.yaml"
TRUTH_VERSION = "2026-10-29.1"
LANGUAGES = ("java", "python", "go")
STYLE = {"ecdsa-p256-sign": "indirect"}  # every other item is `direct`; one call takes its algorithm from a variable
SKIPPED = {"tls13-context"}  # a protocol: the micro scorer scores algorithm records
FORM = 0  # Go's PBKDF2 has two forms; the first is the standard library's (Go 1.24), so the project needs no module
DECOY_EVERY = 2  # a decoy after every second item, the rest at the end
FILES = {"java": "src/main/java/app/CryptoDemo.java", "python": "app/crypto_demo.py", "go": "main.go"}
GO_MOD = "module example.com/microgo\n\ngo 1.24\n"

TRUTH_HEADER = """\
# Ground truth of the micro projects (experiments/corpus/micro/<language>/). GENERATED by `python -m mutation.micro`
# from the snippet catalogs (mutation/catalog/<language>.yaml): edit a catalog or the generator, never this file.
#
# Every expected item is one catalog snippet in a function of its own; `lines` are that function's body, `calls` the
# line naming the algorithm, `expected` the snippet's canonical record. Hit rule (decided 2026-10-22, before any tool
# output on these projects was scored): a tool finds an item when it reports an algorithm record on one of its lines
# whose group (analysis/data/algorithms.yaml `groups`) is the item's `group` (strict) or unknown (lenient); for a
# keygen item (`keygen: true`) a key record (related-crypto-material) of that group counts too. `accepted`: groups
# whose records on a line are neither a hit nor a false site: a sub-use of the item (the snippet's `also` identities
# and its digest) on its lines, and the items' groups on the import lines of their APIs. `related`: the line that holds
# the algorithm in a variable (the indirect style). `decoys`: the catalog's decoys, code that names or resembles
# cryptography without using it; any crypto record there is a false positive. The inclusion
# bar: half of the items, lenient. AI-made like the catalogs; on the human-review list before paper use.
"""


@dataclass
class Step:
    """One function of a generated file: an item (a catalog snippet) or a decoy."""

    name: str
    imports: tuple[str, ...]
    body: list[str]
    snippet: Snippet | None = None
    decoy: Snippet | None = None  # a catalog decoy (`Snippet.decoy`)
    call: int | None = None  # index into `body` of the line naming the algorithm
    related: list[int] = field(default_factory=list)
    first: int = 0  # 1-based line of the body's first line in the file, set when the file is assembled


@dataclass
class Project:
    language: str
    files: dict[str, str]  # path below experiments/corpus/micro/<language>/ -> content
    truth: dict  # the project's entry of ground_truth.yaml


def _steps(language: str, catalog: Catalog) -> list[Step]:
    unit = "\t" if language == "go" else "    "

    def decoy(d: Snippet) -> Step:
        form = d.forms[0]
        template = form.templates["direct"]
        return Step(
            "", form.imports, render(template, {p: p for p in placeholders(template)}, unit=unit).lines, decoy=d
        )

    decoys = list(catalog.decoys)
    steps: list[Step] = []
    for i, snippet in enumerate((s for s in catalog.snippets if s.id not in SKIPPED), start=1):
        form = snippet.forms[FORM]
        template = form.templates[STYLE.get(snippet.id, "direct")]
        r = render(template, {p: p for p in placeholders(template)}, unit=unit)  # one snippet per function: no clash
        steps.append(Step("", form.imports, r.lines, snippet=snippet, call=r.call, related=list(r.related)))
        if i % DECOY_EVERY == 0 and decoys:
            steps.append(decoy(decoys.pop(0)))
    steps += [decoy(d) for d in decoys]
    for n, step in enumerate(steps, start=1):
        step.name = f"step{n:02d}"
    return steps


def _assemble(language: str, steps: list[Step]) -> tuple[str, dict[str, int]]:
    """The file's text and the line of every import; sets every step's `first` body line."""
    imports = sorted({i for s in steps for i in s.imports})
    # No "generated, do not edit" header: scanners skip generated code (xgrep found nothing in a file with one)
    if language == "python":  # `import x` before `from x import y`
        lines = sorted(imports, key=lambda i: (i.startswith("from "), i))
        for s in steps:
            lines += ["", "", f"def {s.name}():"]
            s.first = len(lines) + 1
            lines += ["    " + ln if ln else "" for ln in s.body]
        lines += ["", "", "def main():", *[f"    {s.name}()" for s in steps]]
        lines += ["", "", 'if __name__ == "__main__":', "    main()"]
    elif language == "java":
        lines = ["package app;", "", *[f"import {i};" for i in imports], "", "public class CryptoDemo {"]
        for s in steps:
            lines += [f"    static void {s.name}() throws Exception {{"]
            s.first = len(lines) + 1
            lines += ["        " + ln if ln else "" for ln in s.body] + ["    }", ""]
        lines += ["    public static void main(String[] args) throws Exception {"]
        lines += [f"        {s.name}();" for s in steps] + ["    }", "}"]
    else:
        lines = ["package main", "", "import (", *[f'\t"{i}"' for i in imports], ")"]
        for s in steps:
            lines += ["", f"func {s.name}() {{"]
            s.first = len(lines) + 1
            lines += ["\t" + ln if ln else "" for ln in s.body] + ["}"]
        lines += ["", "func main() {", *[f"\t{s.name}()" for s in steps], "}"]
    spelled = {"python": "{}", "java": "import {};", "go": '\t"{}"'}[language]
    at = {i: lines.index(spelled.format(i)) + 1 for i in imports}
    return "\n".join(lines) + "\n", at


def _group(vocab, identity: str) -> str | None:
    """The coarse group (algorithms.yaml `groups`) of an algorithm or family identity."""
    return vocab.group_of(vocab.family_of_algorithm(identity) or identity)


def project(language: str, vocab) -> Project:
    steps = _steps(language, load_catalog(language))
    text, import_lines = _assemble(language, steps)
    truth: dict = {"path": f"experiments/corpus/micro/{language}", "language": language, "file": FILES[language],
                   "catalog": load_catalog(language).version}  # fmt: skip
    lines, calls, expected, related, decoys = {}, {}, {}, {}, {}
    accepted: dict[int, set[str]] = {}
    for s in steps:
        body = [s.first + i for i, ln in enumerate(s.body) if ln.strip()]
        if s.decoy:
            decoys[s.decoy.id] = {"lines": body, "what": s.decoy.what}
            continue
        sid = s.snippet.id
        lines[sid], calls[sid] = body, s.first + s.call
        expected[sid] = {k: v for k, v in s.snippet.expected.items() if v is not None}
        for r in s.related:
            related[s.first + r] = f"the algorithm of {sid} in a variable, used on line {calls[sid]}"
        own = _group(vocab, s.snippet.expected["family"])
        named = {_group(vocab, x) for x in (*s.snippet.also, s.snippet.expected.get("digest")) if x} - {None}
        for n in body:  # its sub-uses
            accepted.setdefault(n, set()).update(named - {own})
        for i in s.imports:  # an import of the item's API is crypto code too: neither a hit nor a false site
            accepted.setdefault(import_lines[i], set()).update(named | {own})
    accepted = {n: sorted(g) for n, g in sorted(accepted.items()) if g}
    truth.update(lines=lines, calls=calls, expected=expected, related=related, accepted=accepted, decoys=decoys)
    files = {FILES[language]: text, **({"go.mod": GO_MOD} if language == "go" else {})}
    return Project(language, files, truth)


def assets(vocab) -> list[dict]:
    """The expected items over all languages, by catalog id: its group (the same in every catalog), style, keygen."""
    out: dict[str, dict] = {}
    for language in LANGUAGES:
        for s in load_catalog(language).snippets:
            if s.id in SKIPPED:
                continue
            group = _group(vocab, s.expected["family"])
            item = out.setdefault(s.id, {"id": s.id, "group": group})
            if item["group"] != group:
                raise ValueError(f"{s.id}: group {group} in {language}, {item['group']} elsewhere")
            if s.id in STYLE:
                item["insertion_style"] = STYLE[s.id]
            if s.id.endswith("-keygen"):
                item["keygen"] = True
    return list(out.values())


class _Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data) -> bool:  # every list written out, no anchors: the file is read by people
        return True


def generated(vocab=None) -> dict[Path, str]:
    """Every generated file -> its content."""
    from analysis.normalize.vocab import load_vocabulary

    vocab = vocab or load_vocabulary()
    projects = {lg: project(lg, vocab) for lg in LANGUAGES}
    data = {"version": TRUTH_VERSION, "assets": assets(vocab),
            "projects": {f"micro-{lg}": p.truth for lg, p in projects.items()}}  # fmt: skip
    text = yaml.dump(data, Dumper=_Dumper, sort_keys=False, default_flow_style=None, width=120)
    out = {TRUTH_FILE: TRUTH_HEADER + text}
    for lg, p in projects.items():
        out.update({MICRO_DIR / lg / rel: text for rel, text in p.files.items()})
    return out


def main() -> None:
    for path, text in generated().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(path.relative_to(ROOT), file=sys.stderr)


if __name__ == "__main__":
    main()
